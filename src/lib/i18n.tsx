interface I18nContextValue {
  lang: Language;
  locale: string;
  setLang: (lang: Language) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
  tc: (cat: ProductCategory) => string;
  to: (occ: OccasionType) => string;
  tsort: (sort: SortOption) => string;
  tb: (badge: ProductBadge) => string;
  ts: (status: OrderStatus) => string;
  tr: (cls: ReviewClass) => string;
  tsent: (sent: SentimentLabel) => string;
  totab: (tab: OrderTab) => string;
}

const LOCALE_MAP: Record<Language, string> = {
  en: 'en-IN',
  hi: 'hi-IN',
  bn: 'bn-IN',
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    if (typeof window === 'undefined') return 'en';
    const stored = localStorage.getItem('kk_lang');
    if (stored === 'hi' || stored === 'bn' || stored === 'en') return stored;
    return 'en';
  });

  const setLang = (next: Language) => {
    setLangState(next);
    if (typeof window !== 'undefined') {
      localStorage.setItem('kk_lang', next);
      document.documentElement.lang = next;
    }
  };

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
    }
  }, [lang]);

  const t = (key: TranslationKey, vars?: Record<string, string | number>): string => {
    let text = DICTIONARIES[lang][key] ?? EN[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  };

  return (
    <I18nContext.Provider
      value={{
        lang,
        locale: LOCALE_MAP[lang],
        setLang,
        t,
        tc: (cat) => CATEGORY_MAP[lang][cat] ?? cat,
        to: (occ) => OCCASION_MAP[lang][occ] ?? occ,
        tsort: (sort) => SORT_MAP[lang][sort] ?? sort,
        tb: (badge) => BADGE_MAP[lang][badge] ?? badge,
        ts: (status) => STATUS_MAP[lang][status] ?? status,
        tr: (cls) => REVIEW_CLASS_MAP[lang][cls] ?? cls,
        tsent: (sent) => SENTIMENT_MAP[lang][sent] ?? sent,
        totab: (tab) => ORDER_TAB_MAP[lang][tab] ?? tab,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error('useI18n must be used within a LanguageProvider');
  }
  return ctx;
}
