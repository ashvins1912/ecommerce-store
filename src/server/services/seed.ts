function makeOrder(
  id: string,
  orderNumber: string,
  sellerId: string,
  items: Array<{ product: Product; qty: number }>,
  status: OrderStatus,
  daysOld: number,
  tracking?: { companyName: string; trackingId: string; trackingUrl: string }
): Order {
  const totalAmount = items.reduce((sum, i) => sum + i.product.salePrice * i.qty, 0);
  const created = daysAgo(daysOld);
  return {
    _id: id,
    orderNumber,
    buyerId: 'usr_buyer_1',
    buyerName: 'Ananya Mehta',
    sellerId,
    items: items.map(({ product, qty }) => ({
      productId: product._id,
      variantSku: product.variants[0]?.variantSku || product.sku,
      title: product.title,
      size: product.variants[0]?.size || 'Free Size',
      colorName: product.variants[0]?.colorName || 'Standard',
      imageUrl: product.images[0]?.url || IMG.kundanChoker,
      quantity: qty,
      unitPrice: product.salePrice,
    })),
    totalAmount,
    status,
    shippingAddress: {
      fullName: 'Ananya Mehta',
      phone: '+919876543210',
      street: '42B Linking Road, Bandra West',
      city: 'Mumbai',
      state: 'Maharashtra',
      pincode: '400050',
    },
    ...(tracking
      ? {
          courierTracking: {
            ...tracking,
            shippedAt: daysAgo(Math.max(0, daysOld - 1)),
          },
        }
      : {}),
    statusTimeline: [
      { status: 'Pending', note: 'Order placed via Kala & Karat', timestamp: created },
      ...(status !== 'Pending'
        ? [{ status, note: `Order marked as ${status}`, timestamp: daysAgo(Math.max(0, daysOld - 1)) }]
        : []),
    ],
    createdAt: created,
    updatedAt: daysAgo(Math.max(0, daysOld - 1)),
  };
}

